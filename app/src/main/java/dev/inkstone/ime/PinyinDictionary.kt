    fun candidates(pinyin: String): List<String> {
        if (pinyin.isEmpty()) return emptyList()
        entries[pinyin]?.let { return it }
        return entries.asSequence()
            .filter { (key, _) -> key.startsWith(pinyin) }
            .flatMap { it.value.asSequence() }
            .distinct()
            .take(8)
            .toList()
    }
